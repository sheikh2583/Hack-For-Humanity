"""Validation utilities: detection count comparison and closure proximity check.

Input
-----
- **count comparison**: a detection GeoParquet and a user-supplied reference
  CSV with columns ``district`` and ``reported_count``.  The reference file
  must come from a credible source and is NOT generated by this project.
- **closure proximity**: a detection GeoParquet and a user-supplied CSV of
  closed kiln locations with columns ``latitude``, ``longitude`` and optional
  ``closure_year``.  The CSV is NOT generated by this project.

Output
------
- **count comparison**: a dict keyed by district with ``detected``,
  ``reported``, and ``ratio`` fields.
- **closure proximity**: a list of dicts, one per closed-kiln record, with the
  distance to the nearest detection and the detection's class and confidence.

These utilities compare project outputs to external reference data.  They do
**not** invent, download, or fabricate any reference data.  The human must
supply the reference files after sourcing them from published reports, official
registers, or field records.

Contract
--------
>>> from src.eval.validate_counts import compare_district_counts
>>> compare_district_counts(detections_path, reference_csv)
{'Chapainawabganj': {'detected': 120, 'reported': 150, 'ratio': 0.8}}

>>> from src.eval.validate_counts import check_closure_proximity
>>> check_closure_proximity(detections_path, closure_csv)
[{'latitude': 24.0, ..., 'nearest_detection_m': 450.0, ...}]
"""

from __future__ import annotations

import csv
from pathlib import Path
from typing import Any

import geopandas as gpd
import numpy as np

from src.geo.crs import get_projected_crs


def compare_district_counts(
    detections_path: Path,
    reference_csv: Path,
) -> dict[str, dict[str, Any]]:
    """Compare per-district detection counts against a user-supplied reference.

    Parameters
    ----------
    detections_path : Path
        GeoParquet with at least ``district`` and ``geometry`` columns.
    reference_csv : Path
        CSV with ``district`` and ``reported_count`` columns.
        This file must be prepared by the human from a credible source.

    Returns
    -------
    dict[str, dict]
        ``{district: {detected, reported, ratio}}``.
        ``ratio`` is ``detected / reported`` (NaN when reported is 0).
    """
    detections = gpd.read_parquet(detections_path)
    if "district" not in detections.columns:
        raise ValueError("Detections GeoParquet must contain a 'district' column")
    detected_counts = detections.groupby("district").size().to_dict()

    reference: dict[str, int] = {}
    with open(reference_csv, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        if reader.fieldnames is None or not {"district", "reported_count"} <= set(reader.fieldnames):
            raise ValueError("Reference CSV must contain 'district' and 'reported_count' columns")
        for row in reader:
            reference[row["district"]] = int(row["reported_count"])

    all_districts = sorted(set(detected_counts) | set(reference))
    result: dict[str, dict[str, Any]] = {}
    for district in all_districts:
        detected = detected_counts.get(district, 0)
        reported = reference.get(district, 0)
        ratio = float(detected / reported) if reported > 0 else float("nan")
        result[district] = {
            "detected": detected,
            "reported": reported,
            "ratio": round(ratio, 4) if np.isfinite(ratio) else None,
        }
    return result


def check_closure_proximity(
    detections_path: Path,
    closure_csv: Path,
    max_distance_m: float = 5000.0,
) -> list[dict[str, Any]]:
    """Check proximity of closed-kiln locations to the nearest detection.

    Parameters
    ----------
    detections_path : Path
        GeoParquet of detected kilns with ``geometry``, ``class``, and
        ``confidence`` columns.
    closure_csv : Path
        CSV with ``latitude``, ``longitude``, and optional ``closure_year``
        columns.  Must be prepared by the human from a credible source.
    max_distance_m : float
        Maximum search radius in metres (default 5 000 m).  Closed-kiln
        records beyond this distance from any detection get
        ``nearest_detection_m = None``.

    Returns
    -------
    list[dict]
        One record per closed-kiln entry with ``latitude``, ``longitude``,
        ``closure_year``, ``nearest_detection_m``, ``nearest_class``, and
        ``nearest_confidence``.
    """
    from shapely.strtree import STRtree

    proj_crs = get_projected_crs()
    detections = gpd.read_parquet(detections_path).to_crs(proj_crs)

    records: list[dict[str, Any]] = []
    with open(closure_csv, newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        if reader.fieldnames is None or not {"latitude", "longitude"} <= set(reader.fieldnames):
            raise ValueError("Closure CSV must contain 'latitude' and 'longitude' columns")
        for row in reader:
            records.append({
                "latitude": float(row["latitude"]),
                "longitude": float(row["longitude"]),
                "closure_year": row.get("closure_year", ""),
            })

    if not records:
        return []

    closure_gdf = gpd.GeoDataFrame(
        records,
        geometry=gpd.points_from_xy(
            [r["longitude"] for r in records],
            [r["latitude"] for r in records],
        ),
        crs="EPSG:4326",
    ).to_crs(proj_crs)

    results: list[dict[str, Any]] = []

    if detections.empty:
        for rec in records:
            results.append({
                **rec,
                "nearest_detection_m": None,
                "nearest_class": None,
                "nearest_confidence": None,
            })
        return results

    tree = STRtree(detections.geometry.values)

    for idx, closure_geom in enumerate(closure_gdf.geometry):
        nearest_idx = tree.nearest(closure_geom)
        nearest_geom = detections.geometry.values[nearest_idx]
        distance = closure_geom.distance(nearest_geom)

        if distance <= max_distance_m:
            nearest_row = detections.iloc[nearest_idx]
            results.append({
                **records[idx],
                "nearest_detection_m": round(float(distance), 1),
                "nearest_class": str(nearest_row.get("class", "")),
                "nearest_confidence": float(nearest_row.get("confidence", 0.0)),
            })
        else:
            results.append({
                **records[idx],
                "nearest_detection_m": None,
                "nearest_class": None,
                "nearest_confidence": None,
            })

    return results
