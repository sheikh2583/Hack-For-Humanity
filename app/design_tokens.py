# --- WCAG contrast ---------------------------------------------------------
def _linear(channel: float) -> float:
    value = channel / 255
    return value / 12.92 if value <= 0.04045 else ((value + 0.055) / 1.055) ** 2.4


def _rgb(hex_colour: str) -> tuple[int, int, int]:
    text = hex_colour.lstrip("#")
    return int(text[0:2], 16), int(text[2:4], 16), int(text[4:6], 16)


def luminance(hex_colour: str) -> float:
    """Relative luminance of ``#rrggbb`` (WCAG 2.x)."""
    red, green, blue = (_linear(c) for c in _rgb(hex_colour))
    return 0.2126 * red + 0.7152 * green + 0.0722 * blue


def contrast_ratio(foreground: str, background: str) -> float:
    """WCAG contrast ratio between two ``#rrggbb`` colours (1.0 to 21.0)."""
    high, low = sorted((luminance(foreground), luminance(background)), reverse=True)
    return (high + 0.05) / (low + 0.05)


# --- colour-blind simulation (Machado et al. 2009, severity 1.0) -----------
_CVD_MATRICES: dict[str, tuple[tuple[float, float, float], ...]] = {
    "protan": ((0.152286, 1.052583, -0.204868), (0.114503, 0.786281, 0.099216), (-0.003882, -0.048116, 1.051998)),
    "deutan": ((0.367322, 0.860646, -0.227968), (0.280085, 0.672501, 0.047413), (-0.011820, 0.042940, 0.968881)),
    "tritan": ((1.255528, -0.076749, -0.178779), (-0.078411, 0.930809, 0.147602), (0.004733, 0.691367, 0.303900)),
}
CVD_KINDS = tuple(_CVD_MATRICES)


def simulate_cvd(hex_colour: str, kind: str) -> tuple[float, float, float]:
    """Linear-RGB triple of ``hex_colour`` as seen with ``protan``/``deutan``/``tritan`` vision."""
    linear = [_linear(c) for c in _rgb(hex_colour)]
    rows = _CVD_MATRICES[kind]
    return tuple(min(1.0, max(0.0, sum(m * c for m, c in zip(row, linear))))  # type: ignore[return-value]
                 for row in rows)


def _lab(linear: tuple[float, float, float]) -> tuple[float, float, float]:
    red, green, blue = linear
    x = (0.4124 * red + 0.3576 * green + 0.1805 * blue) / 0.95047
    y = 0.2126 * red + 0.7152 * green + 0.0722 * blue
    z = (0.0193 * red + 0.1192 * green + 0.9505 * blue) / 1.08883

    def f(t: float) -> float:
        return t ** (1 / 3) if t > 0.008856 else 7.787 * t + 16 / 116

    fx, fy, fz = f(x), f(y), f(z)
    return 116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)


def delta_e(first: str, second: str, kind: str | None = None) -> float:
    """CIE76 colour distance, optionally after simulating a colour-vision deficiency."""
    def lin(h: str) -> tuple[float, float, float]:
        return simulate_cvd(h, kind) if kind else tuple(_linear(c) for c in _rgb(h))  # type: ignore[return-value]

    a, b = _lab(lin(first)), _lab(lin(second))
    return sum((p - q) ** 2 for p, q in zip(a, b)) ** 0.5


# --- generators ------------------------------------------------------------
def css_variables() -> str:
    """Return a ``:root`` block exposing every token as a ``--dhoa-*`` property."""
    lines = [f"  --dhoa-color-{name.replace('_', '-')}: {value};" for name, value in COLORS.items()]
    lines += [f"  --dhoa-space-{name}: {value};" for name, value in SPACE.items()]
    lines += [f"  --dhoa-radius-{name}: {value};" for name, value in RADII.items()]
    lines += [f"  --dhoa-shadow-{name}: {value};" for name, value in SHADOWS.items()]
    lines += [f"  --dhoa-type-{name}: {value};" for name, value in TYPE_SCALE.items()]
    lines += [f"  --dhoa-lh-{name}: {value};" for name, value in LINE_HEIGHT.items()]
    lines += [f"  --dhoa-weight-{name}: {value};" for name, value in WEIGHTS.items()]
    lines.append(f"  --dhoa-tap: {MIN_TAP_PX}px;")
    lines.append(f"  --dhoa-font: {FONT_STACK};")
    return ":root {\n" + "\n".join(lines) + "\n}\n"


def component_root_block() -> str:
    """The marked ``:root`` block for static iframe components (names in ``_COMPONENT_NAMES``)."""
    lines = [f"        --{css}: {COLORS[token]};" for css, token in _COMPONENT_NAMES.items()]
    return (f"      {COMPONENT_BLOCK_START}\n      :root {{\n" + "\n".join(lines)
            + f"\n      }}\n      {COMPONENT_BLOCK_END}")


def streamlit_theme() -> dict[str, str]:
    """Values for the ``[theme]`` table of ``.streamlit/config.toml``."""
